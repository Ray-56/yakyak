#!/usr/bin/env python3
"""Generate and validate YakYak roadmap views. Python 3.10+, stdlib only.

This tool checks structure and references, not the truth of test results.
It never changes an objective's status and never performs network or Git writes.
"""
from __future__ import annotations

import argparse
from datetime import date
import json
from pathlib import Path
import re
import subprocess
import sys
from typing import Any

STATUSES = {
    "not_started": "未开始",
    "in_progress": "实现中",
    "ready_for_review": "待人工验收",
    "passed": "通过",
    "blocked": "阻塞",
}
GENERATED = "<!-- GENERATED by scripts/roadmap.py; DO NOT EDIT. -->\n"
SHA = re.compile(r"[0-9a-f]{40}")


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object)
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {path}")
    return value


def load(root: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    base = root / "docs" / "roadmap"
    return read_json(base / "targets.json"), read_json(base / "progress.json")


def valid_sha(value: Any) -> bool:
    return isinstance(value, str) and bool(SHA.fullmatch(value)) and value != "0" * 40


def _report(root: Path, ac_id: str, value: Any) -> Path | None:
    if not isinstance(value, str) or not value or "\\" in value:
        return None
    relative = Path(value)
    if relative.is_absolute() or ".." in relative.parts:
        return None
    allowed = root / "docs" / "acceptance" / f"ch{ac_id[3:5]}"
    resolved = (root / relative).resolve()
    if not resolved.is_relative_to(allowed.resolve()) or resolved.suffix != ".md":
        return None
    if not resolved.is_file() or resolved.name.upper() == "README.MD":
        return None
    return resolved


def validate(root: Path, spec: dict[str, Any], progress: dict[str, Any], *, check_git: bool = False) -> list[str]:
    errors: list[str] = []
    if spec.get("schema_version") != 2 or spec.get("project") != "YakYak":
        errors.append("targets.json: unsupported schema/project")
    if spec.get("ai_excluded") is not True:
        errors.append("targets.json: ai_excluded must remain true")
    chapters = spec.get("chapters")
    if not isinstance(chapters, list) or not chapters:
        return errors + ["targets.json: chapters must be a nonempty list"]
    if spec.get("total_chapters") != len(chapters):
        errors.append("targets.json: total_chapters mismatch")
    chapter_map: dict[str, dict[str, Any]] = {}
    objective_map: dict[str, dict[str, Any]] = {}
    for chapter in chapters:
        if not isinstance(chapter, dict):
            errors.append("invalid chapter object")
            continue
        number = chapter.get("number")
        if not isinstance(number, str) or not re.fullmatch(r"\d{2}", number):
            errors.append("chapter number must be two digits")
            continue
        if number in chapter_map:
            errors.append(f"duplicate chapter {number}")
        chapter_map[number] = chapter
        for field in ("title", "phase", "goal", "stop_line"):
            if not isinstance(chapter.get(field), str) or not chapter[field].strip():
                errors.append(f"chapter {number}: missing {field}")
        if not isinstance(chapter.get("references"), list) or not all(isinstance(x, str) for x in chapter.get("references", [])):
            errors.append(f"chapter {number}: references must be a string list")
        objectives = chapter.get("objectives")
        if not isinstance(objectives, list) or not objectives:
            errors.append(f"chapter {number}: objectives must be a nonempty list")
            continue
        for objective in objectives:
            if not isinstance(objective, dict):
                errors.append(f"chapter {number}: invalid objective")
                continue
            ac_id = objective.get("id")
            if not isinstance(ac_id, str) or not re.fullmatch(rf"AC-{number}-\d{{2}}", ac_id):
                errors.append(f"chapter {number}: invalid objective id {ac_id!r}")
                continue
            if ac_id in objective_map:
                errors.append(f"duplicate objective {ac_id}")
            objective_map[ac_id] = objective
            for field in ("title", "exercise", "acceptance", "test_type"):
                if not isinstance(objective.get(field), str) or not objective[field].strip():
                    errors.append(f"{ac_id}: missing {field}")
            if "status" in objective or "evidence" in objective:
                errors.append(f"{ac_id}: mutable status/evidence belongs in progress.json")
    if spec.get("total_objectives") != len(objective_map):
        errors.append("targets.json: total_objectives mismatch")
    graph: dict[str, list[str]] = {}
    for number, chapter in chapter_map.items():
        deps = chapter.get("dependencies")
        if not isinstance(deps, list) or not all(isinstance(x, str) for x in deps):
            errors.append(f"chapter {number}: invalid dependencies")
            continue
        graph[number] = deps
        for dep in deps:
            if dep not in chapter_map or dep == number:
                errors.append(f"chapter {number}: invalid dependency {dep}")
    visited: set[str] = set()
    active: set[str] = set()

    def visit(node: str) -> None:
        if node in active:
            errors.append(f"chapter dependency cycle at {node}")
            return
        if node in visited:
            return
        active.add(node)
        for dep in graph.get(node, []):
            if dep in graph:
                visit(dep)
        active.remove(node)
        visited.add(node)

    for number in graph:
        visit(number)
    if progress.get("schema_version") != 1 or progress.get("project") != "YakYak":
        errors.append("progress.json: unsupported schema/project")
    records = progress.get("objectives")
    if not isinstance(records, dict):
        return errors + ["progress.json: objectives must be an object"]
    missing = set(objective_map) - set(records)
    extra = set(records) - set(objective_map)
    if missing:
        errors.append(f"progress.json: missing IDs {sorted(missing)}")
    if extra:
        errors.append(f"progress.json: unknown IDs {sorted(extra)}")
    for ac_id in sorted(set(objective_map) & set(records)):
        record = records[ac_id]
        if not isinstance(record, dict):
            errors.append(f"{ac_id}: invalid progress record")
            continue
        required = {"status", "implementation_commit", "evidence", "reviewer", "reviewed_at", "note"}
        if not required.issubset(record):
            errors.append(f"{ac_id}: missing progress fields")
        status = record.get("status")
        if not isinstance(status, str) or status not in STATUSES:
            errors.append(f"{ac_id}: unknown status {status!r}")
        note = record.get("note")
        if not isinstance(note, str):
            errors.append(f"{ac_id}: note must be a string")
        if status == "blocked" and (not isinstance(note, str) or not note.strip()):
            errors.append(f"{ac_id}: blocked requires a reason")
        commit = record.get("implementation_commit")
        if commit is not None and not valid_sha(commit):
            errors.append(f"{ac_id}: implementation_commit must be a full nonzero SHA or null")
        evidence = record.get("evidence")
        if not isinstance(evidence, list):
            errors.append(f"{ac_id}: evidence must be a list")
            evidence = []
        for entry in evidence:
            path = _report(root, ac_id, entry)
            if path is None:
                errors.append(f"{ac_id}: report must exist beneath docs/acceptance/ch{ac_id[3:5]}: {entry!r}")
                continue
            if status in ("passed", "ready_for_review"):
                text = path.read_text(encoding="utf-8")
                if ac_id not in text or (valid_sha(commit) and commit not in text):
                    errors.append(f"{ac_id}: report must include AC id and tested commit")
        if status in ("passed", "ready_for_review"):
            if not valid_sha(commit):
                errors.append(f"{ac_id}: {status} requires a real implementation commit")
            if not evidence:
                errors.append(f"{ac_id}: {status} requires an existing acceptance report")
        if status == "passed":
            reviewer = record.get("reviewer")
            if not isinstance(reviewer, str) or not reviewer.strip():
                errors.append(f"{ac_id}: passed requires maintainer review")
            try:
                date.fromisoformat(record.get("reviewed_at") or "")
            except (ValueError, TypeError):
                errors.append(f"{ac_id}: passed requires reviewed_at in YYYY-MM-DD format")
            chapter_number = ac_id[3:5]
            for dep in graph.get(chapter_number, []):
                for needed in chapter_map.get(dep, {}).get("objectives", []):
                    dep_record = records.get(needed.get("id"), {})
                    if not isinstance(dep_record, dict) or dep_record.get("status") != "passed":
                        errors.append(f"{ac_id}: prerequisite chapter {dep} has not passed")
                        break
        if check_git and valid_sha(commit):
            try:
                obj = subprocess.run(["git", "-C", str(root), "cat-file", "-e", f"{commit}^{{commit}}"], capture_output=True, timeout=15, check=False)
                if obj.returncode:
                    errors.append(f"{ac_id}: commit not available in this Git repository")
                else:
                    ancestor = subprocess.run(["git", "-C", str(root), "merge-base", "--is-ancestor", commit, "HEAD"], capture_output=True, timeout=15, check=False)
                    refs = subprocess.run(["git", "-C", str(root), "for-each-ref", "--contains", commit, "--format=%(refname)"], capture_output=True, timeout=15, check=False)
                    if ancestor.returncode and (refs.returncode or not refs.stdout.strip()):
                        errors.append(f"{ac_id}: commit is not reachable from HEAD or a retained ref")
            except (OSError, subprocess.TimeoutExpired) as exc:
                errors.append(f"{ac_id}: Git check failed: {exc}")
    return errors


def cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def chapter_text(chapter: dict[str, Any]) -> str:
    lines = [GENERATED.rstrip(), f"# 第 {chapter['number']} 章：{chapter['title']}", "",
             f"阶段：{chapter['phase']}；直接依赖：{', '.join(chapter['dependencies']) or '无'}。", "",
             f"**本章目标：**{chapter['goal']}", "", f"**停止线：**{chapter['stop_line']}", "",
             "动态状态只看 [PROGRESS.md](../PROGRESS.md)，不要在本文件手改通过状态。", "", "## 逐项目标与验收", ""]
    for ac in chapter["objectives"]:
        lines += [f"### {ac['id']}｜{ac['title']}", "", f"**要实现/执行：**{ac['exercise']}", "",
                  f"**通过标准：**{ac['acceptance']}", "", f"**验证方式：**{ac['test_type']}", ""]
    lines += ["## 本章完成检查", "", "按 TESTING_CONTRACT.md 逐项验证；不适用维度解释原因。每项具备真实commit、命令、结果和证据，经过人工确认后才能通过。", "",
              "## 参考阅读", "", "、".join(chapter["references"]) + "。完整来源见 [SOURCES.md](../SOURCES.md)。", ""]
    return "\n".join(lines)


def views(root: Path, spec: dict[str, Any], progress: dict[str, Any]) -> dict[str, str]:
    chapters = spec["chapters"]
    result: dict[str, str] = {}
    for chapter in chapters:
        result[f"docs/roadmap/chapters/{chapter['number']}.md"] = chapter_text(chapter)
    index = [GENERATED.rstrip(), "# YakYak 章节索引", "", f"{len(chapters)}章 / {spec['total_objectives']}项目标；AI排除。要求来自targets.json，状态来自progress.json。", "",
             "先完成第00章的真实环境与评审，不能把初始化脚手架等同于整章通过。第09章是第一道通信内核关卡。", "",
             "| 章 | 主题 | 阶段 | 依赖 | 目标数 |", "|---|---|---|---|---:|"]
    for ch in chapters:
        index.append(f"| {ch['number']} | [{cell(ch['title'])}](chapters/{ch['number']}.md) | {ch['phase']} | {', '.join(ch['dependencies']) or '无'} | {len(ch['objectives'])} |")
    index += ["", "[范围](SCOPE.md) · [验收契约](TESTING_CONTRACT.md) · [当前进度](PROGRESS.md) · [完整阅读版](ROADMAP.md)", ""]
    result["docs/roadmap/INDEX.md"] = "\n".join(index)
    records = progress["objectives"]
    counts = {status: sum(r["status"] == status for r in records.values()) for status in STATUSES}
    lines = [GENERATED.rstrip(), "# YakYak 当前进度", "", "唯一状态源：progress.json。此页自动生成，不手动勾选。", "",
             "；".join(f"{STATUSES[k]} {v}" for k, v in counts.items()) + "。", "",
             "初始化项目的完成不自动构成功能目标通过；passed需要人工确认及可复验记录。", ""]
    for ch in chapters:
        lines += [f"## 第 {ch['number']} 章：{ch['title']}", "", "| AC | 目标 | 状态 | 实现commit | 报告 |", "|---|---|---|---|---|"]
        for ac in ch["objectives"]:
            r = records[ac["id"]]
            sha = f"`{r['implementation_commit'][:12]}`" if r["implementation_commit"] else "—"
            reports = "、".join(f"[报告{i+1}](../{p.removeprefix('docs/')})" for i, p in enumerate(r["evidence"])) or "—"
            lines.append(f"| {ac['id']} | {cell(ac['title'])} | {STATUSES[r['status']]} | {sha} | {reports} |")
        lines.append("")
    result["docs/roadmap/PROGRESS.md"] = "\n".join(lines)
    base = root / "docs" / "roadmap"
    whole = [GENERATED.rstrip(), "# YakYak 通信引擎完整路线图", "", "这是自动生成的需求阅读版，不是完成报告；动态状态见PROGRESS.md。", "",
             "初始化交接位于docs/handoff/BOOTSTRAP.md；它只委托工程基础，不自动授权后续通信实现。", "",
             (base / "SCOPE.md").read_text(encoding="utf-8"), "\n---\n", (base / "TESTING_CONTRACT.md").read_text(encoding="utf-8"), "\n---\n"]
    for chapter in chapters:
        text = chapter_text(chapter).replace(GENERATED, "").replace("../PROGRESS.md", "PROGRESS.md").replace("../SOURCES.md", "SOURCES.md")
        whole += [text, "\n---\n"]
    whole += [(base / "SOURCES.md").read_text(encoding="utf-8")]
    result["docs/roadmap/ROADMAP.md"] = "\n".join(whole).rstrip() + "\n"
    return result


def check_views(root: Path, outputs: dict[str, str]) -> list[str]:
    errors = []
    for relative, text in outputs.items():
        path = root / relative
        if not path.is_file():
            errors.append(f"missing generated file: {relative}")
        elif path.read_text(encoding="utf-8") != text:
            errors.append(f"generated file drift: {relative}")
    directory = root / "docs" / "roadmap" / "chapters"
    expected = {Path(p).name for p in outputs if p.startswith("docs/roadmap/chapters/")}
    if directory.exists():
        for path in directory.glob("[0-9][0-9].md"):
            if path.name not in expected:
                errors.append(f"unexpected generated chapter: {path.name}; review manually")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    commands = parser.add_subparsers(dest="command", required=True)
    validation = commands.add_parser("validate", help="check data, IDs, statuses and report references")
    validation.add_argument("--git", action="store_true", help="also check commit existence/reachability")
    rendering = commands.add_parser("render", help="regenerate deterministic Markdown views")
    rendering.add_argument("--check", action="store_true", help="compare only; never write")
    show = commands.add_parser("show", help="print one objective and its current status")
    show.add_argument("id")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        spec, progress = load(root)
        errors = validate(root, spec, progress, check_git=getattr(args, "git", False))
        if errors:
            for error in errors:
                print(f"ERROR: {error}", file=sys.stderr)
            return 1
        if args.command == "validate":
            print(f"OK: {spec['total_chapters']} chapters, {spec['total_objectives']} objectives; structure only, not functional acceptance")
        elif args.command == "render":
            outputs = views(root, spec, progress)
            if args.check:
                errors = check_views(root, outputs)
                if errors:
                    for error in errors:
                        print(f"ERROR: {error}", file=sys.stderr)
                    return 1
                print(f"OK: {len(outputs)} generated files match (read-only check)")
            else:
                for relative, text in outputs.items():
                    path = root / relative
                    if path.is_symlink():
                        raise ValueError(f"refusing to overwrite symlink: {relative}")
                    if not path.resolve().is_relative_to(root):
                        raise ValueError(f"output escapes root: {relative}")
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8")
                print(f"Generated {len(outputs)} files; objective statuses unchanged")
        else:
            for chapter in spec["chapters"]:
                for objective in chapter["objectives"]:
                    if objective["id"] == args.id:
                        print(json.dumps({"chapter": chapter["number"], "requirement": objective, "progress": progress["objectives"][args.id]}, ensure_ascii=False, indent=2))
                        return 0
            print(f"ERROR: unknown objective {args.id}", file=sys.stderr)
            return 2
        return 0
    except (OSError, ValueError, KeyError, TypeError, RecursionError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
